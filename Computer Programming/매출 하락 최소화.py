def solution(sales, links):
    # 전체 직원 수
    n = len(sales)


    # children[x] = x번 인덱스 직원의 직속 팀원 목록
    # 직원번호는 문제에서 1부터 시작하지만,Python에서는 편하게 0부터 시작하도록 변환해서 사용한다.
    children = [[] for _ in range(n)]


    # links에는 [팀장, 팀원] 관계가 들어있다.
    # 문제의 직원번호는 1부터 시작하므로 Python 인덱스로 사용하기 위해 각각 -1 한다.
    for parent, child in links:
        children[parent - 1].append(child - 1)


    # dp[x][0] : x가 워크숍에 "불참"할 때 x 아래의 모든 팀 조건을 만족시키는 최소 비용
    # dp[x][1] : x가 워크숍에 "참석"할 때 x 아래의 모든 팀 조건을 만족시키는 최소 비용
    dp = [[0, 0] for _ in range(n)]


    # ---------------------------------------------------
    # DP를 계산할 순서를 만들기 위한 DFS
    # ---------------------------------------------------

    # order에는 트리를 위 → 아래 방향으로 방문한 순서를 저장한다.
    order = []

    # CEO는 직원번호 1번이고, 0-based 인덱스에서는 0번이므로 0에서 시작한다.
    stack = [0]


    # stack을 이용해서 트리를 순회한다.
    # 직원 수가 최대 300,000명이므로
    while stack:

        # 현재 방문할 직원
        x = stack.pop()

        # 방문한 직원을 order에 저장
        order.append(x)

        # x의 모든 직속 팀원을 stack에 넣는다.
        for child in children[x]:
            stack.append(child)


    # ---------------------------------------------------
    # Tree DP 시작
    # ---------------------------------------------------

    # order는 부모 → 자식 순서로 만들어졌다.
    # 하지만 부모의 DP를 계산하려면 자식의 DP가 먼저 계산되어 있어야 한다.
    # 따라서 reversed(order)를 이용해서 아래 → 위 방향으로 계산한다.
    for x in reversed(order):


        # ==================================================
        # Case 1. x가 워크숍에 참석하는 경우
        # ==================================================

        # x가 참석하므로 우선 x 자신의 매출액을 비용으로 추가한다.
        dp[x][1] = sales[x]


        # x의 자식들을 확인한다.
        for child in children[x]:

            # x가 이미 참석했으므로 x가 팀장인 팀은 이미 "최소 한 명 참석" 조건을 만족한다.
            # 따라서 각각의 child는 참석 / 불참 중 더 저렴한 상태를 자유롭게 선택할 수 있다.
            # dp[child][0] = child 불참
            # dp[child][1] = child 참석
            dp[x][1] += min(dp[child][0], dp[child][1])


        # ==================================================
        # Leaf node 처리
        # ==================================================

        # 자식이 없으면 x는 팀장이 아니다.
        # 따라서 x가 불참한다고 해도 x가 책임져야 할 하위 팀이 존재하지 않는다.
        if not children[x]:

            # 불참하면 비용 0
            dp[x][0] = 0

            # 이 노드의 계산은 끝났으므로 다음 노드로 이동
            continue


        # ==================================================
        # Case 2. x가 워크숍에 불참하는 경우
        # ==================================================

        # 자식들의 최소 비용을 저장할 변수
        base = 0

        # x가 불참하면 자식 중 최소 한 명은 반드시 참석해야 한다.
        # 그 한 명을 참석시키는 데 필요한 최소 추가 비용을 저장한다.
        # 최소값을 찾아야 하므로 처음에는 무한대로 설정한다.
        min_extra = float('inf')


        # x의 모든 자식을 확인한다.
        for child in children[x]:

            # 우선 각 자식에 대해 참석 / 불참 중 더 저렴한 상태를 선택한다.
            # 이 단계에서는 아직 "자식 중 최소 한 명 참석" 조건을 고려하지 않는다.
            base += min(dp[child][0], dp[child][1])


            # ------------------------------------------------
            # child를 참석시키기 위한 추가 비용 계산
            # ------------------------------------------------
            extra = max(0, dp[child][1] - dp[child][0])


            # 여러 자식 중 참석시키는 데 필요한 추가 비용이 가장 작은 자식을 찾는다.
            min_extra = min(min_extra, extra)


        # x가 불참하는 경우의 최종 비용
        # base: 각 자식의 가장 저렴한 상태들의 합
        # min_extra: x가 불참했기 때문에 자식 중 최소 한 명을 참석시키기 위해 필요한 최소 추가 비용
        dp[x][0] = base + min_extra


    # ---------------------------------------------------
    # 최종 정답
    # ---------------------------------------------------

    # 0번 인덱스 = CEO
    # CEO도 워크숍에 반드시 참석해야 하는 것은 아니다.
    # 따라서 CEO 불참 상태와 CEO 참석 상태 중 더 작은 비용이 전체 최솟값이다.
    return min(dp[0][0], dp[0][1])
